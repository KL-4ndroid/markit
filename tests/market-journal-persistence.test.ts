import 'fake-indexeddb/auto';
import assert from 'node:assert/strict';
import { db, generateUUID, clearAllData } from '../lib/db';
import { MarketJournalRepository, type JournalCloudPort } from '../lib/markets/market-journal-repository';
import { assertJournalRevision, buildJournalEntries, journalHasConflict, journalMarketDates, validateJournalInput, type MarketJournal, type MarketJournalDraft } from '../lib/markets/market-journal';
import { runJournalRequest } from '../lib/markets/market-journal-request';
import { getLocalPendingWriteReport } from '../lib/sync/local-pending-write-report';
import { guardedAuthenticatedCacheReset } from '../lib/sync/authenticated-cache-reset-guard';
import { resolveAccountDeletionPreflight } from '../lib/subscription/account-deletion-preflight';
import { hasScheduleMarketUserActivity } from '../lib/recurring-operations/reconciliation';
import { invalidateJournalCacheScope } from '../lib/markets/market-journal-cache-scope';
import { installNetworkPort } from '../lib/platform/network-capability';

async function main() {
  const restoreNetwork = installNetworkPort({getCurrentStatus:()=>({connected:true,connectionType:'unknown'}),subscribe:()=>()=>{}});
  process.env.NEXT_PUBLIC_MARKET_JOURNALS_ENABLED = 'true';
  await db.open(); await clearAllData();
  const market = { id:'journal-market', owner_id:'owner', name:'Test', location:'Test', dates:['2026-10-23','2026-10-25'], startDate:'2026-10-23', endDate:'2026-10-25', status:'completed' as const, createdAt:1,updatedAt:1, totalRevenue:500, totalDeals:2, notes:'shared host note' };
  await db.markets.put(market);
  assert.deepEqual(journalMarketDates(market),market.dates);
  assert.throws(() => validateJournalInput('hello','2026-10-24',market),/營業日期/);
  assert.throws(() => validateJournalInput(' \n ',null,market),/請先/);
  assert.throws(() => validateJournalInput('字'.repeat(5001),null,market),/最多/);
  assert.equal(validateJournalInput(' 😀\r\n體驗 ',null,market).body,'😀\n體驗');
  assert.deepEqual(journalMarketDates({startDate:'2026-02-30',endDate:'2026-03-01'}),[]);
  const rows = new Map<string, MarketJournal>();
  let offline = false; let loseAck = false; let actor = 'owner';
  const cloud: JournalCloudPort = {
    async assertIdentity(owner) { if (actor !== owner) throw new Error('JOURNAL_SCOPE'); },
    async list(owner) { if (offline) throw new Error('offline'); return [...rows.values()].filter(r=>r.ownerId===owner); },
    async save(draft,deleted) {
      if (offline) throw new Error('offline');
      const previous = rows.get(draft.id);
      if(previous?.mutationId===draft.mutationId) return previous;
      if((previous?.revision??0)!==draft.baseRevision) throw new Error('JOURNAL_CONFLICT');
      const row: MarketJournal = {id:draft.id,ownerId:draft.ownerId,marketId:draft.marketId,authorId:draft.ownerId,businessDate:draft.businessDate,body:draft.body,revision:(previous?.revision??0)+1,mutationId:draft.mutationId,createdAt:previous?.createdAt??'2026-10-23T00:00:00Z',updatedAt:'2026-10-23T02:00:00Z',deletedAt:deleted?'2026-10-23T02:00:00Z':null};
      rows.set(row.id,row);
      if(loseAck) { loseAck=false; throw new Error('lost response'); }
      return row;
    },
  };
  let repo = new MarketJournalRepository('owner',cloud);
  const draft: MarketJournalDraft = {id:generateUUID(),ownerId:'owner',marketId:market.id,businessDate:'2026-10-23',body:'四點後人潮最多\n停車要提早。',baseRevision:0,mutationId:generateUUID(),updatedAt:1,deleted:false};
  assert.throws(()=>assertJournalRevision(draft,{revision:1,mutationId:'other'}),/JOURNAL_CONFLICT/);
  assert.doesNotThrow(()=>assertJournalRevision(draft,{revision:1,mutationId:draft.mutationId}));
  let aborted = false;
  await assert.rejects(runJournalRequest(signal => new Promise(() => {signal.addEventListener('abort',()=>{aborted=true;});}),5),/JOURNAL_TIMEOUT/);
  assert.equal(aborted,true,'unresponsive requests release the caller and abort HTTP work');
  const resetNetwork = installNetworkPort({getCurrentStatus:()=>({connected:false,connectionType:'none'}),subscribe:()=>()=>{}});
  await assert.rejects(repo.save(draft),/JOURNAL_OFFLINE/);
  assert.equal(rows.size,0,'known offline status must prevent the writer even if the external network remains reachable');
  resetNetwork();
  offline = true;
  await assert.rejects(repo.save(draft),/offline/);
  assert.deepEqual(await db.marketJournalDrafts.get(draft.id),draft);
  assert.equal(rows.size,0);
  const report = await getLocalPendingWriteReport('owner');
  assert.equal(report.pendingMarketJournalDraftCount,1);
  assert.ok(report.blockingReasonCodes.includes('local_pending_market_journal'));
  let resetCalls=0;
  const blocked = await guardedAuthenticatedCacheReset({scope:'full',reason:'manual_signout',userId:'owner',allowSyncAttempt:true},{getReport:async()=>report,push:async()=>{throw new Error('must not auto-send journals');},reset:async()=>{resetCalls++;}});
  assert.equal(blocked.decision,'blocked'); assert.equal(resetCalls,0);
  assert.equal(resolveAccountDeletionPreflight({report,safeExportAvailable:true}).outcome,'blocked');
  assert.ok(hasScheduleMarketUserActivity({hasPrivateJournals:true}));
  offline=false; loseAck=true;
  await assert.rejects(repo.save(draft),/lost response/);
  assert.equal((await db.marketJournalDrafts.get(draft.id))?.mutationId,draft.mutationId);
  await repo.refresh();
  assert.equal(journalHasConflict(draft,await db.marketJournals.get(draft.id)),false,'a lost acknowledgement cannot disable the safe retry button');
  await repo.save(draft);
  assert.equal(rows.get(draft.id)?.revision,1,'lost acknowledgement retry is idempotent');
  assert.equal(await db.marketJournalDrafts.count(),0);
  const next = {...draft,body:'保留新的草稿',baseRevision:1,mutationId:generateUUID()};
  await repo.stage(next);
  await assert.rejects(repo.stage({...next,body:'another tab',mutationId:generateUUID()}),/JOURNAL_DRAFT_CONFLICT/);
  assert.equal((await db.marketJournalDrafts.get(draft.id))?.body,next.body);
  rows.set(draft.id,{...rows.get(draft.id)!,body:'另一裝置已更新',revision:2,mutationId:generateUUID()});
  await assert.rejects(repo.save(next),/JOURNAL_CONFLICT/);
  await repo.refresh();
  assert.equal((await db.marketJournalDrafts.get(draft.id))?.body,next.body,'cloud refresh cannot overwrite a draft');
  assert.equal(journalHasConflict(next,await db.marketJournals.get(draft.id)),true);
  const merged = {...next,baseRevision:2,mutationId:generateUUID()};
  await repo.stage(merged,next.mutationId); await repo.save(merged);
  const removed = {...merged,baseRevision:3,mutationId:generateUUID(),deleted:true};
  await repo.save(removed);
  assert.ok((await db.marketJournals.get(draft.id))?.deletedAt);
  await repo.save({...removed,baseRevision:4,mutationId:generateUUID(),deleted:false});
  assert.equal((await db.marketJournals.get(draft.id))?.deletedAt,null);
  await db.marketJournals.clear(); await repo.refresh();
  assert.equal((await db.marketJournals.get(draft.id))?.body,merged.body);
  const cached = (await db.marketJournals.toArray());
  assert.equal(buildJournalEntries({ownerId:'owner',markets:[market],journals:cached,drafts:[],query:'保留'}).length,1);
  assert.equal(buildJournalEntries({ownerId:'owner',markets:[market],journals:cached,drafts:[],regionCode:'tw-tainan-city'}).length,0);
  assert.equal(buildJournalEntries({ownerId:'staff',markets:[market],journals:cached,drafts:[draft]}).length,0);
  assert.equal(buildJournalEntries({ownerId:'owner',markets:[{...market,isDeleted:true}],journals:cached,drafts:[draft]}).length,0);
  assert.equal(buildJournalEntries({ownerId:'owner',markets:[market],journals:cached.map(j=>({...j,deletedAt:'2026-10-23'})),drafts:[]}).length,0);
  assert.equal(buildJournalEntries({ownerId:'owner',markets:[market],journals:cached.map(j=>({...j,deletedAt:'2026-10-23'})),drafts:[],showRemoved:true}).length,1);
  assert.deepEqual(await db.markets.get(market.id),market,'journals cannot change money, status or host notes');
  assert.equal(await db.events.count(),0,'private text never enters shared events');
  actor='staff';
  await assert.rejects(repo.save({...merged,mutationId:generateUUID()}),/JOURNAL_SCOPE/);
  await assert.rejects(new MarketJournalRepository('staff',cloud).stage({...draft,ownerId:'staff'}),/JOURNAL_SCOPE/);
  actor='owner'; invalidateJournalCacheScope();
  await assert.rejects(repo.stage(draft),/JOURNAL_SCOPE/,'late work cannot repopulate cache after reset');
  repo = new MarketJournalRepository('owner',cloud);
  await db.markets.update(market.id,{isDeleted:true});
  await assert.rejects(repo.stage(draft),/JOURNAL_SCOPE/);
  restoreNetwork(); db.close();
}
main().then(()=>console.log('PASS private journals: drafts, conflicts, idempotency, rebuild, privacy and reset guards')).catch(e=>{console.error(e);db.close();process.exitCode=1;});
