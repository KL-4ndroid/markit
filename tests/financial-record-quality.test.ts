import assert from 'node:assert/strict';
import { assessDailyFinancialRecord, assessFixedMarketFee, classifyFinancialAmount, dailyFinancialBasis, marketFeeBasis } from '../lib/analytics/financial-record-quality';
import type { DailyStats,Market } from '../types/db';
const market={id:'m',name:'fixture',location:'fixture',startDate:'2026-10-01',endDate:'2026-10-02',dates:['2026-10-01','2026-10-02'],status:'completed',boothCost:0,registrationFee:0,createdAt:0,updatedAt:0} as Market;
const stat={marketId:'m',date:'2026-10-01',revenue:1000,cost:0,profit:1000,dealCount:1,touchCount:0,inquiryCount:0,productsSold:[],updatedAt:0} as DailyStats;
assert.equal(classifyFinancialAmount(undefined),'unknown');
assert.equal(classifyFinancialAmount(0),'unknown');
assert.equal(classifyFinancialAmount(0,true),'confirmed-zero');
assert.equal(classifyFinancialAmount(-1,true),'invalid');
assert.equal(classifyFinancialAmount(NaN,true),'invalid');
assert.equal(classifyFinancialAmount(Infinity),'invalid');
assert.equal(classifyFinancialAmount(200),'recorded');
const costProof={kind:'zero-sales-cost' as const,basis:dailyFinancialBasis(stat)};
assert.equal(assessDailyFinancialRecord(stat).costUsable,false);
assert.equal(assessDailyFinancialRecord(stat,[costProof]).costUsable,true);
assert.equal(assessDailyFinancialRecord(stat,[{kind:'zero-income',basis:dailyFinancialBasis(stat)}]).costUsable,false,'invalid income confirmation must not imply zero cost');
assert.equal(assessDailyFinancialRecord({...stat,revenue:2000,profit:2000},[costProof]).costUsable,false,'changed financial source invalidates confirmation');
assert.equal(assessDailyFinancialRecord({...stat,updatedAt:100},[costProof]).costUsable,true,'unrelated refresh timestamp must not invalidate finance');
assert.equal(assessDailyFinancialRecord({...stat,marketId:'another'},[costProof]).costUsable,false);
assert.equal(assessDailyFinancialRecord({...stat,date:'2026-10-02'},[costProof]).costUsable,false);
const zero={...stat,revenue:0,profit:0,dealCount:0};
assert.equal(assessDailyFinancialRecord(zero).zeroIncomeConfirmed,false);
assert.equal(assessDailyFinancialRecord(zero,[{kind:'zero-income',basis:dailyFinancialBasis(zero)}]).zeroIncomeConfirmed,true);
assert.equal(assessDailyFinancialRecord({...zero,dealCount:1},[{kind:'zero-income',basis:dailyFinancialBasis({...zero,dealCount:1})}]).zeroIncomeConfirmed,false);
assert.equal(assessDailyFinancialRecord({...stat,cost:200,profit:900}).costUsable,false);
assert.equal(assessDailyFinancialRecord({...stat,dealCount:Number.MAX_SAFE_INTEGER+1}).revenueValid,false);
const feeProof={kind:'zero-fixed-fee' as const,basis:marketFeeBasis(market)};
assert.equal(assessFixedMarketFee(market,0),'unknown');
assert.equal(assessFixedMarketFee(market,0,[feeProof]),'confirmed-zero');
assert.equal(assessFixedMarketFee({...market,notes:'unrelated'},0,[feeProof]),'confirmed-zero');
assert.equal(assessFixedMarketFee({...market,dates:['2026-10-02']},0,[feeProof]),'unknown');
assert.equal(assessFixedMarketFee({...market,boothCost:-100},0),'invalid');
assert.equal(assessFixedMarketFee({...market,tableRental:-100,tableFree:true},0,[feeProof]),'unknown');
console.log('PASS amount knowledge, source-bound zero confirmation, no implied zero income, invalid values and independent fee sources');
