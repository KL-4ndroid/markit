import assert from 'node:assert/strict';
import React from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import { MarketPaymentDeadlineFields } from '../components/markets/MarketPaymentDeadlineFields';
import { MarketPlanningOverview } from '../components/home/MarketPlanningOverview';
import { buildMarketPlanningViewModel } from '../lib/markets/market-planning-view-model';
import type { Market } from '../types/db';

const deadline = { date: '2026-10-24', time: '12:00', timeZone: 'Asia/Taipei' as const, reminderEnabled: false };
process.env.NEXT_PUBLIC_MARKET_PAYMENT_DEADLINE_ENABLED = 'true';
const html = renderToStaticMarkup(<MarketPaymentDeadlineFields id="deadline" value={deadline} onChange={() => {}} />);
assert.match(html, /for="deadline"/);
assert.match(html, /截止日期/);
assert.match(html, /截止時間（選填）/);
assert.match(html, /清除時間，改為當日結束前/);
assert.match(html, /移除期限/);
assert.match(html, /在 App 內顯示期限提醒/);
assert.doesNotMatch(html, /checked=""/);
assert.match(html, /台灣時間；未填時間為當日結束前/);
assert.match(html, /aria-label="查看期限提醒方式" aria-haspopup="dialog"/);
process.env.NEXT_PUBLIC_MARKET_PAYMENT_DEADLINE_ENABLED = 'false';
const paused = renderToStaticMarkup(<MarketPaymentDeadlineFields id="deadline" onChange={() => {}} />);
assert.match(paused, /繳費期限準備中/);
assert.match(paused, /disabled=""/);
const market = { id: 'm', name: 'Test', location: 'Test', startDate: '2026-11-01', endDate: '2026-11-01', status: 'accepted', paymentDeadline: { ...deadline, reminderEnabled: true } } as Market;
const planning = buildMarketPlanningViewModel([market], new Date('2026-10-24T13:00:00+08:00'));
const overview = renderToStaticMarkup(<MarketPlanningOverview planning={planning} onOpenProgress={() => {}} />);
assert.match(overview, /逾期 1 場/);
assert.match(overview, /aria-describedby="payment-deadline-summary"/);
assert.match(overview, /grid-cols-2/);
console.log('PASS optional deadline fields, opt-out rendering, clear controls and accessible reminder tile');
