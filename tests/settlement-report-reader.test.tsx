import assert from 'node:assert/strict';
import React from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import { SettlementReportReader } from '../components/reports/settlement/SettlementReportReader';
import { deriveRoleCapabilities } from '../lib/permissions/role-capabilities';
import { buildReadableSettlementReport } from '../lib/reporting/settlement-report-reading';
import { buildSettlementReportPreviewModel } from '../lib/reporting/settlement-report-preview';
import { formatCurrency } from '../lib/presentation/formatters';
import type { Market, Product, DailyStats } from '../types/db';

const capabilities = deriveRoleCapabilities({isOwner:true,staffRole:null});
const timestamp = Date.parse('2026-10-29T00:00:00Z');
const market = {id:'m1',name:'<市集>&長名稱',location:'台南',startDate:'2026-10-01',endDate:'2026-10-01',status:'completed',boothCost:100,registrationFee:0,totalRevenue:1000,totalDeals:2,totalInteractions:3,createdAt:timestamp,updatedAt:timestamp,sync_status:'synced'} as Market;
const product = {id:'p1',name:'測試商品',category:'other',price:500,cost:100,isActive:true,createdAt:timestamp,updatedAt:timestamp} as Product;
const stat = {marketId:'m1',date:'2026-10-01',revenue:1000,cost:200,profit:800,dealCount:2,touchCount:2,inquiryCount:1,productsSold:[{productId:'p1',quantity:2,revenue:1000}],updatedAt:timestamp} as DailyStats;
function build(markets: Market[],dailyStats:DailyStats[]) {
  const report = buildReadableSettlementReport({capabilities,generatedAtDate:'2026-10-29',brandName:'測試品牌',period:{kind:'monthly',startDate:'2026-10-01',endDate:'2026-10-31',label:'2026/10'},markets,dailyStats,products:[product]});
  const preview = buildSettlementReportPreviewModel({capabilities,report});
  return {report,preview};
}
const {report,preview} = build([market],[stat]);
const render = (props={report,preview,productIds:['p1']})=>renderToStaticMarkup(<SettlementReportReader {...props} exportActions={<button>測試匯出</button>} />);
const html = render();
for (const id of ['overview','markets','products','costs']) assert.ok(html.includes(`id="${id}"`));
assert.doesNotMatch(html,/id="quality"|aria-label="市集排序"/,'no empty warning or one-market sorting control');
assert.ok(html.includes(formatCurrency(report.money.totalRevenue)));
assert.ok(html.includes(formatCurrency(report.money.netProfit)));
assert.ok(html.includes('&lt;市集&gt;&amp;長名稱'));
assert.ok(html.includes('reportStart=2026-10-01'));
assert.ok(html.includes('reportEnd=2026-10-31'));
assert.match(html,/<table/);
assert.match(html,/md:hidden/);
assert.match(html,/<details><summary[^>]*>匯出 PDF（選用）/);
assert.doesNotMatch(html,/<iframe|<object|blob:|download=/);
for(const issue of report.reading!.issues) assert.ok(html.includes(issue.title));
const noProductLink=render({report,preview,productIds:[]});
assert.ok(noProductLink.includes('商品資料待補齊'));
assert.doesNotMatch(noProductLink,/products\/detail\?/);
const limited = render({report,preview:{...preview,header:{...preview.header,showFormalScores:false},nextActions:['不應出現的再次參加結論'],reliability:{...preview.reliability,limitations:Array.from({length:4},(_,i)=>({code:`gap-${i}`,message:`缺資料${i}`,recommendation:`補紀錄${i}`,affectedSections:['market_performance'],severity:'warning' as const,placement:'top' as const}))}},productIds:['p1']});
assert.doesNotMatch(limited,/>評分依據</);
assert.doesNotMatch(limited,/不應出現的再次參加結論/);
assert.doesNotMatch(limited,/id="quality"/,'legacy preview limitations must not manufacture report actions');
assert.doesNotMatch(limited,/資料信心度|覆蓋收入的|report\.decision\.score/);
assert.match(limited,/依目前商品成本估算，非成交當時成本/);
const empty = build([],[]);
assert.match(render({...empty,productIds:[]}),/此期間沒有可納入回顧的市集/);
assert.doesNotMatch(render({...empty,productIds:[]}),/待確認|信心|成本待補/);
const many = build(Array.from({length:20},(_,i)=>({...market,id:`m${i}`})),[]);
assert.match(render({...many,productIds:[]}),/已顯示 5／20 場/);
const restored=renderToStaticMarkup(<SettlementReportReader {...many} productIds={[]} view={{markets:15,products:5,sort:'date',focusMarket:'m12'}} exportActions={null} />);
assert.match(restored,/已顯示 15／20 場/);assert.match(restored,/繼續查看/);assert.match(restored,/id="market-m12"/);
console.log('PASS reader actual model totals, chapters, responsive markup, disclosure, safe links, quality guards and empty/long periods');

const incomplete=build([market,{...market,id:'missing'}],[stat]);
const partialHtml=render({...incomplete,productIds:['p1']});
assert.match(partialHtml,/已確認 1 場估計淨利小計/);
assert.match(partialHtml,/不代表全期淨利/);
assert.match(partialHtml,/id="quality"/);
assert.match(partialHtml,/有商品明細收入/);
assert.match(partialHtml,/目前庫存/);
const unknownCosts=build([market],[{...stat,cost:0,profit:1000}]);
const costHtml=render({...unknownCosts,productIds:['p1']});
assert.match(costHtml,/task=performance[^"<]*reportDate=2026-10-01/);
assert.doesNotMatch(costHtml,/task=costs/,'sales cost must not navigate to fixed-equipment costs');
const progress=build([{...market,status:'ongoing',startDate:'2026-10-29',endDate:'2026-10-29'}],[{...stat,date:'2026-10-29'}]);
const progressHtml=render({...progress,productIds:['p1']});
assert.doesNotMatch(progressHtml,/id="quality"/);
assert.match(progressHtml,/href="#costs"[^>]*>待確認/,'status-only pending profit must target a visible explanation');
console.log('PASS scoped profit, no empty warnings, one-market controls, sales-cost date routing and status-only anchors');
