/** Build a rollback-only SQL check; this script never connects to a database. */
import { readFileSync, writeFileSync } from 'node:fs';
import { getDealEventCost, getDealEventCount, getDealEventRevenue } from '../lib/events/event-read-model';

const fixtures = JSON.parse(readFileSync('tests/fixtures/deal-projection-contract.json', 'utf8')) as {
  name: string; payload: Record<string, unknown>; expected: number[];
}[];
const cases = fixtures.map(fixture => {
  const event = { payload: fixture.payload };
  return { ...fixture, expected: [getDealEventRevenue(event), getDealEventCost(event), getDealEventCount(event)] };
});
const quote = (value: string) => `'${value.replaceAll("'", "''")}'`;
const migration = readFileSync('supabase/migrations/073_align_cloud_deal_projections.sql', 'utf8')
  .replace(/^BEGIN;$/m, '').replace(/^COMMIT;$/m, '');
const checks = readFileSync('tests/sql/073_deal_projection_assertions.sql', 'utf8');
const baseline = JSON.parse(readFileSync('.codex-artifacts/bw11-rollback-baseline.json', 'utf8')) as Record<string, string>;
for (const field of ['data', 'market', 'product', 'helpers']) {
  if (!/^[a-f0-9]{32}$/.test(baseline[field])) throw new Error(`Invalid read-only baseline: ${field}`);
}
const sql = `-- GENERATED by scripts/build-deal-projection-verification.ts. Rollback only.
BEGIN;
SET LOCAL statement_timeout = '30s';
${migration}
-- Reapply inside the same rollback transaction to verify migration idempotence.
${migration}
DO $contract$
DECLARE fixture JSONB; actual NUMERIC[];
BEGIN
  FOR fixture IN SELECT * FROM jsonb_array_elements(${quote(JSON.stringify(cases))}::JSONB) LOOP
    SELECT ARRAY[t.revenue,t.cost,t.deal_count] INTO actual FROM public.deal_projection_totals(fixture->'payload') t;
    IF to_jsonb(actual) <> fixture->'expected' THEN
      RAISE EXCEPTION 'Shared contract mismatch: % actual %', fixture->>'name', actual;
    END IF;
  END LOOP;
END;
$contract$;
${checks}
ROLLBACK;
-- Rollback must restore the fixture AND both function definitions exactly.
DO $restored$
DECLARE actual_hash TEXT;
BEGIN
  WITH rows AS (
    SELECT 'market' AS kind, to_jsonb(m) AS value FROM public.markets m WHERE id = 'f69d8d90-667c-4af0-ad00-4c52e60aafa8'
    UNION ALL SELECT 'event', to_jsonb(e) FROM public.events e WHERE market_id = 'f69d8d90-667c-4af0-ad00-4c52e60aafa8'
    UNION ALL SELECT 'product', to_jsonb(p) FROM public.products p WHERE id = 'ffbdbf76-0b85-4206-8519-a81d09bce12c'
  ) SELECT md5(string_agg(value::TEXT, '' ORDER BY kind, value::TEXT)) INTO actual_hash FROM rows;
  IF actual_hash IS DISTINCT FROM '${baseline.data}'
    OR md5(pg_get_functiondef('public.update_market_read_model()'::regprocedure)) <> '${baseline.market}'
    OR md5(pg_get_functiondef('public.update_product_read_model()'::regprocedure)) <> '${baseline.product}'
    OR (SELECT md5(COALESCE(string_agg(pg_get_functiondef(p.oid), '' ORDER BY p.proname),''))
      FROM pg_proc p JOIN pg_namespace n ON n.oid=p.pronamespace WHERE n.nspname='public'
      AND p.proname IN ('deal_projection_number','deal_projection_totals','deal_projection_delta')) <> '${baseline.helpers}'
    OR EXISTS (SELECT 1 FROM public.events WHERE metadata->>'verification' = 'BW10-073-rollback-only')
    OR EXISTS (SELECT 1 FROM public.products WHERE name LIKE '[BW10-073-rollback-only]%') THEN
    RAISE EXCEPTION 'Rollback did not restore all verification evidence';
  END IF;
END;
$restored$;
SELECT 'PASS: shared totals / normal / manual / backfill / delete / duplicate / out-of-order / scope / legacy / stock; all changes rolled back' AS result;
`;
const target = process.argv[2] ?? '.codex-artifacts/bw10-073-rollback.sql';
writeFileSync(target, sql);
console.log(`Wrote rollback-only verification: ${target}`);
